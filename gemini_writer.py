#!/usr/bin/env python3
"""
gemini_writer.py: does the morning routine's job with Google's Gemini (free tier) instead of Claude.

It checks today's candidates (watermark, safety), picks two (your picks.txt choices first), writes
each one's replica prompt, short prompt and 2-line caption, and saves exactly the files the Claude
routine saves, so posting works the same. The rules are read from morning_task.md, so both writers
always follow the same instructions.

Which writer runs is set in writer.txt:
  claude   (default) the Claude routine writes; Gemini only steps in if nothing is written by ~7 AM
  gemini   Gemini writes right after the 5 AM frames; the Claude routine stands down

  python3 gemini_writer.py                 write today's prompts now (skips if already written)
  python3 gemini_writer.py --if-mode gemini   same, only when writer.txt says gemini
  python3 gemini_writer.py --compare [DAY] write Gemini's version of the videos Claude chose, to
                                           tests/gemini/<day>/ (changes nothing else)

Secret: GEMINI_API_KEY (aistudio.google.com). Optional: GEMINI_MODEL to force a model.
"""
import base64
import datetime as dt
import glob
import json
import os
import re
import sys
import time

import requests

ROOT = os.path.dirname(os.path.abspath(__file__))
TZ = dt.timezone(dt.timedelta(hours=5, minutes=45))
API = "https://generativelanguage.googleapis.com/v1beta"
SLOT_TIME = {1: "4:30 PM", 2: "9:30 PM"}


def env(k):
    return os.environ.get(k, "").strip()


def log(m):
    print(m, flush=True)


def writer_mode():
    p = os.path.join(ROOT, "writer.txt")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            w = line.split("#")[0].strip().lower()
            if w in ("claude", "gemini"):
                return w
    return "claude"


# ---------- rules (taken from morning_task.md so Claude and Gemini follow the same ones) ----------

def rules():
    t = open(os.path.join(ROOT, "morning_task.md"), encoding="utf-8").read()
    step3 = re.search(r"(STEP 3 —.*?)\nSTEP 4 —", t, re.S)
    step3 = step3.group(1).replace("Before saving, review", "Before answering, review") if step3 else ""
    cap = re.search(r'("caption": exactly TWO lines.*?)\n', t)
    short = re.search(r'("prompt_short":.*?)\n', t)
    return f"""You recreate short AI videos so they can be regenerated with Seedance 2.5 (in Dola AI).
For ONE candidate video you get: its metadata, timestamped frame grids (each frame stamped with its time
in yellow, top-left: we add those stamps, ignore them), bottom-of-frame strips (subtitles / on-screen text),
and the text of the original creator's page (it contains the creator's own prompt; use it for intent,
dialogue and sound; where it disagrees with the frames, follow the frames).

FIRST, CHECK THE CANDIDATE. It FAILS if:
- it is sexual or graphically violent (gore);
- it has a WATERMARK: anything burned in on top of the picture that isn't part of the scene: an app or
  AI-tool name or logo (e.g. "Wizstar AI", "Dola AI", "Kling", "Hailuo", "Jimeng", "Vidu", "Pika", "Runway",
  "Sora", "Veo", "Seedance", "Dreamina", "CapCut"), a creator @handle or website, a "made with"/"generated by"
  label, or any small fixed logo, even faint or semi-transparent, in any corner, along any edge or in the
  centre. If you're unsure, it fails.
Do NOT fail a video because it features copyrighted characters, a franchise cast or real people: keep it and
replace them as the rules below say.

IF IT PASSES, write its prompt following these rules exactly:
{step3}

ALSO WRITE:
- caption: {cap.group(1) if cap else 'exactly TWO short lines, one sentence each; line 1 the hook, line 2 names the model.'}
- prompt_short: {short.group(1).split(':', 1)[1].strip() if short else 'the prompt condensed to at most 270 characters.'}
- hook_score: 1-10, how likely the clip is to stop someone scrolling.

Reply with ONLY this JSON object:
{{"pass": true|false, "watermark": true|false, "fail_reason": "<why it failed, or null>",
 "title": "<short title>", "hook_score": <1-10>, "characters_swapped": true|false,
 "caption": "<line 1>\\n<line 2>", "prompt": "<full prompt or null>", "prompt_short": "<or null>"}}"""


# ---------- Gemini ----------

def models():
    """Free Flash models, newest first (e.g. gemini-3.8-flash, gemini-3.6-flash)."""
    if env("GEMINI_MODEL"):
        return [env("GEMINI_MODEL")]
    r = requests.get(f"{API}/models", params={"key": env("GEMINI_API_KEY"), "pageSize": 200}, timeout=30)
    r.raise_for_status()
    names = [m["name"].split("/", 1)[1] for m in r.json().get("models", [])
             if "generateContent" in m.get("supportedGenerationMethods", [])]
    flash = [n for n in names if re.fullmatch(r"gemini-\d+(\.\d+)?-flash", n)]
    flash.sort(key=lambda n: [int(x) for x in re.findall(r"\d+", n)], reverse=True)
    return flash or [n for n in names if "flash" in n and "lite" not in n][:3]


def ask(parts, system):
    last = None
    for model in models():
        for attempt in range(2):
            r = requests.post(f"{API}/models/{model}:generateContent", params={"key": env("GEMINI_API_KEY")},
                              timeout=600, json={
                                  "systemInstruction": {"parts": [{"text": system}]},
                                  "contents": [{"role": "user", "parts": parts}],
                                  "generationConfig": {"responseMimeType": "application/json",
                                                       "temperature": 0.4, "maxOutputTokens": 32768}})
            if r.status_code == 429:  # this model's free quota is used up: try the next model
                last = f"{model}: quota reached"
                log(f"  {last}")
                break
            if r.status_code >= 300:
                last = f"{model}: {r.status_code} {r.text[:300]}"
                log(f"  {last}")
                time.sleep(5)
                continue
            j = r.json()
            text = "".join(p.get("text", "") for c in j.get("candidates", [])[:1]
                           for p in c.get("content", {}).get("parts", []) if not p.get("thought"))
            try:
                start, end = text.find("{"), text.rfind("}")
                out = json.loads(text[start:end + 1])
                u = j.get("usageMetadata", {})
                log(f"  {model}: {u.get('promptTokenCount')} in + {u.get('candidatesTokenCount')} out tokens")
                out["_model"] = model
                return out
            except Exception as e:
                last = f"{model}: unreadable reply ({e})"
                log(f"  {last}")
    raise RuntimeError(f"Gemini couldn't answer: {last}")


def image(path):
    return {"inline_data": {"mime_type": "image/jpeg", "data": base64.b64encode(open(path, "rb").read()).decode()}}


def study(day, v):
    """Ask Gemini to check one candidate and, if it passes, write its prompt and caption."""
    folder = os.path.join(ROOT, v["dir"])
    meta = json.load(open(os.path.join(folder, "meta.json"), encoding="utf-8"))
    page = os.path.join(folder, "creator_page.txt")
    parts = [{"text": "METADATA (meta.json):\n" + json.dumps(meta, ensure_ascii=False, indent=1)},
             {"text": "FRAME GRIDS (time stamped top-left of each frame):"}]
    parts += [image(f) for f in sorted(glob.glob(os.path.join(folder, "frames_*.jpg")))]
    parts.append({"text": "BOTTOM STRIPS (subtitles / on-screen text):"})
    parts += [image(f) for f in sorted(glob.glob(os.path.join(folder, "text_*.jpg")))]
    if os.path.exists(page):
        parts.append({"text": "ORIGINAL CREATOR'S PAGE (text):\n" + open(page, encoding="utf-8").read()[:30000]})
    parts.append({"text": "Check this candidate, then (if it passes) write its prompt, prompt_short and caption. "
                          "Reply with the JSON object only."})
    out = ask(parts, rules())
    out["meta"] = meta
    if out.get("pass"):
        p = (out.get("prompt") or "").strip()
        if not p:
            raise RuntimeError("passed but no prompt was written")
        if not p.lower().startswith("use seedance 2.5 for this"):
            p = "use seedance 2.5 for this\n\n" + p
        out["prompt"] = p
        out["prompt_short"] = (out.get("prompt_short") or "").strip()[:270]
        lines = [l.strip() for l in (out.get("caption") or "").splitlines() if l.strip()]
        out["caption"] = "\n".join(lines[:2])
    return out


# ---------- saving (same files as the Claude routine) ----------

def save(day, chosen):
    """chosen: {slot: (index_entry, result)}"""
    xdir = os.path.join(ROOT, "prompts", "x")
    os.makedirs(xdir, exist_ok=True)
    for slot, (v, res) in chosen.items():
        json.dump({"date": day, "slot": slot, "slug": v["slug"], "caption": res["caption"],
                   "prompt": res["prompt"], "prompt_short": res["prompt_short"], "writer": res["_model"]},
                  open(os.path.join(xdir, f"{day}-{slot}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    v, res = chosen.get(2) or chosen.get(1)
    m = res["meta"]
    w, h = m.get("width") or 16, m.get("height") or 9
    ratio = "16:9" if w / h > 1.5 else "9:16" if h / w > 1.5 else "1:1" if abs(w - h) < 10 else f"{w}:{h}"
    today_md = (f"DATE: {day}\nSTATUS: READY\nTITLE: {res.get('title') or m.get('title')}\n"
                f"LENGTH: {round(m.get('duration') or 0)} seconds, {ratio}\n\n"
                "MAIN PROMPT — generate ONE video from everything between the two lines below:\n"
                f"----- START -----\n{res['prompt']}\n----- END -----\n")
    for name in ("today.md", f"{day}.md"):
        open(os.path.join(ROOT, "prompts", name), "w", encoding="utf-8").write(today_md)
    parts = os.path.join(ROOT, "prompts", "today-parts.md")
    if os.path.exists(parts):
        os.remove(parts)


def mark_used(urls):
    p = os.path.join(ROOT, "used.json")
    used = json.load(open(p)) if os.path.exists(p) else []
    used += [u for u in urls if u and u not in used]
    json.dump(used[-50000:], open(p, "w"), indent=1)


def telegram(text):
    try:
        sys.path.insert(0, ROOT)
        import daily_report
        if env("TG_BOT_TOKEN"):
            daily_report.tg("sendMessage", chat_id=daily_report.chat_id(), text=text, parse_mode="HTML",
                            disable_web_page_preview=True)
    except Exception as e:
        log(f"(Telegram message not sent: {e})")


# ---------- main jobs ----------

def write(day):
    if any(os.path.exists(os.path.join(ROOT, "prompts", "x", f"{day}-{s}.json")) for s in (1, 2)):
        log(f"Prompts for {day} are already written; nothing to do.")
        return
    index = os.path.join(ROOT, "days", day, "index.json")
    if not os.path.exists(index):
        sys.exit(f"No frames for {day} yet.")
    videos = json.load(open(index)).get("videos", [])
    passed, skipped, wm_urls = [], [], []
    for v in videos:
        if len(passed) >= 2:
            break
        log(f"Checking: {v['title']}")
        try:
            res = study(day, v)
        except Exception as e:
            log(f"  failed: {e}")
            skipped.append(f"{v['title']} (couldn't be written: {str(e)[:80]})")
            continue
        if res.get("pass"):
            passed.append((v, res))
            log(f"  passes (hook {res.get('hook_score')}): {res['caption']!r}")
        else:
            reason = res.get("fail_reason") or "failed the checks"
            log(f"  skipped: {reason}")
            skipped.append(f"{v['title']} ({reason})")
            if res.get("watermark"):
                wm_urls += [v.get("url"), res["meta"].get("x_post")]
    if not passed:
        mark_used(wm_urls)
        telegram(f"⚠️ <b>Mira AI {day}</b>: Gemini found no usable video today.\n" + "\n".join(skipped))
        sys.exit("No candidate passed.")
    picks = [p for p in passed if p[0].get("user_pick")]
    auto = [p for p in passed if not p[0].get("user_pick")]
    if len(picks) >= 2:
        picks.sort(key=lambda p: p[0].get("pick_order", 9))
        chosen = {1: picks[0], 2: picks[1]}
    elif len(picks) == 1:
        chosen = {2: picks[0]}
        if auto:
            chosen[1] = auto[0]
    elif len(passed) == 1:
        chosen = {2: passed[0]}
    else:
        a, b = sorted(passed[:2], key=lambda p: p[1].get("hook_score") or 0)
        chosen = {1: a, 2: b}
    save(day, chosen)
    mark_used(wm_urls)
    log(f"Saved prompts for {day}: " + ", ".join(f"slot {s}: {v['slug']}" for s, (v, _) in sorted(chosen.items())))
    import html as h
    msg = [f"📝 <b>Mira AI {day}: today's videos</b> (written by {passed[0][1]['_model']})"]
    for s in sorted(chosen):
        v, res = chosen[s]
        m = res["meta"]
        links = f'<a href="{h.escape(m.get("url") or "")}">source</a>' + (
            f' · <a href="{h.escape(m["x_post"])}">original X post</a>' if m.get("x_post") else "")
        msg.append(f"\n🎬 <b>{SLOT_TIME[s]}</b>: {h.escape(res.get('title') or v['title'])}\n"
                   f"{h.escape(res['caption'])}\n{links}")
    if skipped:
        msg.append("\nSkipped: " + h.escape("; ".join(skipped)))
    telegram("\n".join(msg))


def compare(day):
    """Gemini's version of the two videos Claude chose, saved next to Claude's for comparison."""
    out_dir = os.path.join(ROOT, "tests", "gemini", day)
    os.makedirs(out_dir, exist_ok=True)
    index = {v["slug"]: v for v in json.load(open(os.path.join(ROOT, "days", day, "index.json")))["videos"]}
    md = [f"# Claude vs Gemini: {day}", ""]
    for s in (1, 2):
        p = os.path.join(ROOT, "prompts", "x", f"{day}-{s}.json")
        if not os.path.exists(p):
            continue
        claude = json.load(open(p, encoding="utf-8"))
        v = index.get(claude["slug"])
        if not v:
            continue
        log(f"Slot {s}: {v['title']}")
        res = study(day, v)
        res.pop("meta", None)
        json.dump(res, open(os.path.join(out_dir, f"{s}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        md += [f"## {SLOT_TIME[s]}: {v['title']}", "",
               f"Gemini model: {res.get('_model')} · check: {'PASS' if res.get('pass') else 'FAIL: ' + str(res.get('fail_reason'))}"
               f" · hook score: {res.get('hook_score')}", "",
               "### Caption", "", "**Claude:**", "", "```", claude["caption"], "```", "", "**Gemini:**", "", "```",
               res.get("caption") or "", "```", "",
               "### Short prompt", "", "**Claude:** " + claude.get("prompt_short", ""), "",
               "**Gemini:** " + (res.get("prompt_short") or ""), "",
               "### Full prompt: Claude", "", "```", claude["prompt"], "```", "",
               "### Full prompt: Gemini", "", "```", res.get("prompt") or "", "```", ""]
    open(os.path.join(out_dir, "compare.md"), "w", encoding="utf-8").write("\n".join(md))
    log(f"Comparison saved to tests/gemini/{day}/compare.md")


def main():
    if not env("GEMINI_API_KEY"):
        sys.exit("GEMINI_API_KEY is missing.")
    args = sys.argv[1:]
    day = dt.datetime.now(TZ).date().isoformat()
    if "--compare" in args:
        rest = [a for a in args if a != "--compare"]
        compare(rest[0] if rest else day)
    elif "--if-mode" in args:
        want = args[args.index("--if-mode") + 1]
        if writer_mode() != want:
            log(f"Writer is set to {writer_mode()}; Gemini doesn't write now.")
            return
        write(day)
    else:
        write(day)


if __name__ == "__main__":
    try:
        main()
    except BaseException as e:
        if os.environ.get("GITHUB_ACTIONS") and not (isinstance(e, SystemExit) and not e.code):
            print(f"::error title=Gemini writer::{str(e)[:500] or type(e).__name__}", flush=True)
        raise
